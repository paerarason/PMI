"""B0 — feature-recognition accuracy regression.

Scores live recognizer output against the curated golden baseline (`tests/fr_golden/`). Any recognizer
change that drops or mis-parametrises an existing feature fails here. When a change *adds* real detections
(e.g. the B2 pocket/slot recognizers), regenerate the golden with `scripts/gen_fr_golden.py` and review the
diff — a shrink in feature counts is a regression, a reviewed growth is the new baseline.
"""
import pytest

from app import config
from app.services.feature_recognition import recognize_features
from app.services.step_loader import load_step
from fr_harness import load_golden, score, to_golden_features

SAMPLES = [
    "demo_bracket_pmi.step",
    "demo_shaft_pmi.step",
    "comprehensive_pmi.step",
    "ap242_mbd_tolerance_sample.step",
    "demo_pocket_features.step",
    "demo_pocket_filleted.step",
]


@pytest.mark.parametrize("sample", SAMPLES)
def test_recognition_matches_golden(sample):
    if not (config.SAMPLES_DIR / sample).exists():
        pytest.skip(f"{sample} is a local file, not generated by scripts/make_samples.py")
    feats = recognize_features(load_step(str(config.SAMPLES_DIR / sample)).shape)
    predicted = to_golden_features(feats)
    result = score(predicted, load_golden(sample))
    assert result.precision == 1.0 and result.recall == 1.0, f"{sample}\n{result.report()}"
    assert not result.param_mismatches, f"{sample}\n{result.report()}"


def test_scorer_detects_a_missing_feature():
    """Guard the harness itself: dropping a golden feature must show up as recall < 1."""
    golden = [{"type": "hole", "diameter": 10.0}, {"type": "hole", "diameter": 16.0}]
    predicted = [{"type": "hole", "params": {"diameter": 10.0}}]
    s = score(predicted, golden)
    assert s.recall == 0.5 and s.precision == 1.0


def test_scorer_detects_a_param_drift():
    """Guard the harness: a diameter outside tolerance is flagged as a param mismatch."""
    golden = [{"type": "hole", "diameter": 10.0}]
    predicted = [{"type": "hole", "params": {"diameter": 12.0}}]
    s = score(predicted, golden)
    assert s.param_mismatches and s.recall == 1.0
