"""B1 — edge convex/concave/tangent classification (topology.py).

These assertions *pin the sign convention*: the bracket is a flat plate with two through-holes, so every
real (two-face) edge must be **convex** — a hole rim on a plate is a 90° peak, never a valley. If the
convention ever flips, this file goes red first, in one place, instead of every prismatic recognizer
silently mis-reading pockets as bosses.
"""
from app import config
from app.services.feature_recognition.topology import build_topology
from app.services.step_loader import load_step
from app.services.tessellator import iter_edges


def _topo(name):
    return build_topology(load_step(str(config.SAMPLES_DIR / name)).shape)


def _cyl_internal_rims(topo):
    """Edge ids where a plane meets an internal cylinder (a hole rim)."""
    out = []
    for eid, fids in topo.edge_faces.items():
        if len(fids) != 2:
            continue
        kinds = {topo.faces[f].surface_type for f in fids}
        sides = {topo.faces[f].material_side for f in fids}
        if kinds == {"plane", "cylinder"} and "internal" in sides:
            out.append(eid)
    return out


def test_flat_plate_has_no_concave_edges():
    """demo_bracket: rectangular plate + 2 through-holes → all feature edges convex, none concave.
    This is the ground-truth sign pin."""
    topo = _topo("demo_bracket_pmi.step")
    assert topo.concave_edges == set()          # a flat plate has no valleys
    assert len(topo.convex_edges) > 0
    # Both hole rims classify convex (a plate hole rim is a peak, not a valley).
    rims = _cyl_internal_rims(topo)
    assert rims, "expected plane↔internal-cylinder hole rims on the bracket"
    assert all(topo.convexity(e) == "convex" for e in rims)


def test_stepped_shaft_has_concave_shoulders():
    """demo_shaft: a stepped shaft's shoulder (shoulder plane meeting the smaller journal) is a concave
    inner corner."""
    topo = _topo("demo_shaft_pmi.step")
    assert len(topo.concave_edges) >= 1
    # every concave edge here involves an external cylinder (the journal) against a shoulder plane
    for e in topo.concave_edges:
        kinds = {topo.faces[f].surface_type for f in topo.edge_faces[e]}
        assert "cylinder" in kinds and "plane" in kinds


def test_comprehensive_has_all_three_kinds():
    """The comprehensive part (counterbore, boss, slot, fillet, hemisphere) exercises convex, concave and
    tangent edges together — including a smooth fillet/blend detected as tangent."""
    topo = _topo("comprehensive_pmi.step")
    assert len(topo.convex_edges) > 0
    assert len(topo.concave_edges) > 0
    tangents = [e for e, k in topo.edge_convexity.items() if k == "tangent"]
    assert tangents, "expected at least one tangent (smooth blend) edge"


def test_every_two_face_edge_is_classified_and_robust():
    """Invariants across all samples: no exception; every 2-face edge gets a real class; 'unknown' is only
    for non-manifold/seam edges; convex and concave sets are disjoint and consistent with edge_convexity."""
    for name in ("demo_bracket_pmi.step", "demo_shaft_pmi.step",
                 "comprehensive_pmi.step", "ap242_mbd_tolerance_sample.step"):
        if not (config.SAMPLES_DIR / name).exists():
            continue                                  # a local file, not generated by scripts/make_samples.py
        topo = _topo(name)
        assert topo.convex_edges.isdisjoint(topo.concave_edges)
        assert topo.convex_edges == {e for e, k in topo.edge_convexity.items() if k == "convex"}
        assert topo.concave_edges == {e for e, k in topo.edge_convexity.items() if k == "concave"}
        for eid, fids in topo.edge_faces.items():
            if len(fids) == 2:
                assert topo.convexity(eid) in ("convex", "concave", "tangent", "unknown")
            else:
                assert topo.convexity(eid) == "unknown"     # seam / non-manifold


def test_per_face_edge_lists_match_global_sets():
    """Every concave/convex edge is recorded on both of its faces, and vice versa."""
    topo = _topo("comprehensive_pmi.step")
    for eid in topo.concave_edges:
        for f in topo.edge_faces[eid]:
            assert eid in topo.faces[f].concave_edge_ids
    for eid in topo.convex_edges:
        for f in topo.edge_faces[eid]:
            assert eid in topo.faces[f].convex_edge_ids
