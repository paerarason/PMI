"""PMI extraction: XCAF path on the linked demo, Part-21 fallback on the unlinked sample, parser unit checks."""
import pytest

from app import config
from app.services.pmi_part21 import parse_step_entities


def test_demo_characteristics(demo_model):
    chars = {c["id"]: c for c in demo_model["characteristics"]}
    assert demo_model["pmi_source"] == "xcaf"
    assert len(chars) == 7
    by_name = {c["feature_name"]: c for c in chars.values()}
    bore = by_name["bore diameter"]
    assert bore["kind"] == "dimension" and bore["type_label"] == "Diameter"
    assert bore["nominal"] == 16.0 and abs(bore["lsl"] - 15.98) < 1e-9 and abs(bore["usl"] - 16.05) < 1e-9
    assert bore["requirement"] == "Ø16 +0.05/-0.02"
    assert len(bore["face_ids"]) == 1 and bore["anchor"] and bore["label_pos"]
    length = by_name["length"]
    assert length["nominal"] == 100.0 and len(length["face_ids"]) == 2
    pos = by_name["bore position"]
    assert pos["kind"] == "geom_tolerance" and pos["usl"] == 0.2 and pos["lsl"] == 0.0
    assert pos["datum_refs"] == ["A", "B"] and pos["symbol"] == "⌖"
    perp = by_name["Side face squareness"]
    assert perp["type_label"] == "Perpendicularity" and perp["datum_refs"] == ["A"]
    assert {d["label"] for d in demo_model["datums"]} == {"A", "B"}
    assert all(d["face_ids"] for d in demo_model["datums"])
    # every characteristic references a face that exists in the mesh
    assert all(all(0 <= f < demo_model["face_count"] for f in c["face_ids"]) for c in chars.values())


def test_mesh_endpoint(client, demo_model):
    r = client.get(f"/api/models/{demo_model['model_id']}/mesh")
    assert r.status_code == 200
    m = r.json()
    assert len(m["positions"]) % 3 == 0 and len(m["indices"]) % 3 == 0
    assert len(m["face_ranges"]) == demo_model["face_count"]
    assert m["face_ranges"][-1]["index_start"] + m["face_ranges"][-1]["index_count"] == len(m["indices"])
    assert m["edges"] and all(len(e["points"]) % 3 == 0 for e in m["edges"])
    assert m["vertices"] and all(len(v["point"]) == 3 for v in m["vertices"])
    # vertex_ids are unique and 0-based contiguous, same convention as face_id/edge_id
    assert sorted(v["vertex_id"] for v in m["vertices"]) == list(range(len(m["vertices"])))


def test_unlinked_sample_falls_back_to_part21(client):
    if not (config.SAMPLES_DIR / "ap242_mbd_tolerance_sample.step").exists():
        pytest.skip("ap242_mbd_tolerance_sample.step is a local file, not generated by scripts/make_samples.py")
    r = client.post("/api/models/samples/ap242_mbd_tolerance_sample.step")
    assert r.status_code == 200, r.text
    m = r.json()
    assert m["pmi_source"] == "part21"
    types = sorted(c["type_label"] for c in m["characteristics"])
    assert types == ["Flatness", "Perpendicularity"]
    perp = next(c for c in m["characteristics"] if c["type_label"] == "Perpendicularity")
    assert perp["usl"] == 0.1 and perp["datum_refs"] == ["A"]
    assert all(c["anchor"] is not None for c in m["characteristics"])  # placed even without face links
    assert any("not linked" in w for w in m["warnings"])


def test_part21_tokenizer_handles_exponent_and_complex():
    text = """DATA;
#1 = MEASURE_WITH_UNIT(5.E-02,#9);
#2 = ( GEOMETRIC_TOLERANCE('n','',#1,#3) GEOMETRIC_TOLERANCE_WITH_DATUM_REFERENCE((#4)) POSITION_TOLERANCE() );
#3 = SHAPE_ASPECT('it''s','',#4,.T.);
ENDSEC;"""
    ents = parse_step_entities(text)
    assert ents[1].args[0][0] == 0.05
    assert ents[2].types == ["GEOMETRIC_TOLERANCE", "GEOMETRIC_TOLERANCE_WITH_DATUM_REFERENCE", "POSITION_TOLERANCE"]
    assert ents[3].args[0][0] == "it's"


